const SkeletonItem = () => (
  <div className="border rounded-2xl shadow-sm bg-gray-50 animate-pulse">
    <div className="px-6 py-4 flex justify-between items-center">
      <div className="h-6 bg-gray-300 rounded w-3/4"></div>
      <div className="w-8 h-8 bg-gray-300 rounded-full"></div>
    </div>
  </div>
);

export default function ProductFaq() {
  const [items, setItems] = useState([]);
  const [isLoading, setIsLoading] = useState(true);
  const [openIndex, setOpenIndex] = useState(null);

  useEffect(() => {
    // Имитация загрузки + рандомизация
    setTimeout(() => {
      const shuffled = [...faqs].sort(() => Math.random() - 0.5);
      setItems(shuffled.slice(0, 4));
      setIsLoading(false);
    }, 800);
  }, []);

  const toggle = (i) => setOpenIndex(openIndex === i ? null : i);

  return (
    <section className="container mx-auto p-6 bg-white">
      <h2 className="text-3xl font-bold mb-8">Частые вопросы</h2>

      <div className="space-y-4">
        {isLoading
          ? Array(4)
              .fill()
              .map((_, i) => <SkeletonItem key={i} />)
          : items.map((faq, i) => (
              <div key={i} className="border rounded-2xl shadow-sm bg-gray-50">
                <button
                  onClick={() => toggle(i)}
                  className="w-full text-left px-6 py-4 flex justify-between items-center font-semibold text-lg"
                >
                  {faq.question}
                  <span className="text-2xl">
                    {openIndex === i ? "−" : "+"}
                  </span>
                </button>

                <div
                  className={`overflow-hidden transition-all duration-500 ${
                    openIndex === i ? "max-h-96" : "max-h-0"
                  }`}
                >
                  <div className="px-6 pb-6 text-gray-700">{faq.answer}</div>
                </div>
              </div>
            ))}
      </div>
    </section>
  );
}
